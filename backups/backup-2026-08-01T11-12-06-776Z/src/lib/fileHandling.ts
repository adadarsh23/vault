const parseMaxUploadSizeMb = () => {
  const rawValue = import.meta.env.VITE_MAX_FILE_SIZE_MB
  const parsed = Number.parseInt(rawValue ?? '', 10)
  return Number.isFinite(parsed) && parsed > 0 ? parsed : 500
}

