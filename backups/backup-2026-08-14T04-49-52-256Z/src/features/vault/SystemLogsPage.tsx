import React, { memo, Suspense, lazy, useCallback, useEffect } from 'react';
import { ArrowLeft } from 'lucide-react';
import { Button } from '../../components/ui/Button';

const SystemLogsCard = lazy(() =>
  import('./components/SettingsVault/SystemLogsCard').then((module) => ({
    default: module.SystemLogsCard,
  }))
);

interface SystemLogsPageProps {
  onBack: () => void;
}

const SystemLogsLoading = () => (
  <div className="flex min-h-[420px] items-center justify-center rounded-2xl border border-card-border bg-card-bg p-8">
    <div className="flex flex-col items-center gap-4">
      <div className="h-10 w-10 animate-spin rounded-full border-4 border-primary/20 border-t-primary" />
      <div className="space-y-2 text-center">
        <p className="text-sm font-medium text-text">Loading System Logs...</p>
        <p className="text-xs text-text/60">Preparing security telemetry and audit events.</p>
      </div>
    </div>
  </div>
);

const SystemLogsPage: React.FC<SystemLogsPageProps> = ({ onBack }) => {
  const handleBack = useCallback(() => {
    onBack();
  }, [onBack]);

  useEffect(() => {
    const previousTitle = document.title;

    document.title = 'System Logs • Artemis Vault';

    window.scrollTo({
      top: 0,
      behavior: 'smooth',
    });

    performance.mark('system-logs-page-open');

    const handleKeyDown = (event: KeyboardEvent) => {
      if (event.key === 'Escape') {
        handleBack();
      }
    };

    window.addEventListener('keydown', handleKeyDown);

    return () => {
      document.title = previousTitle;

      performance.mark('system-logs-page-close');

      try {
        performance.measure('SystemLogsPage', 'system-logs-page-open', 'system-logs-page-close');
      } catch {
        // Ignore duplicate performance marks.
      }

      window.removeEventListener('keydown', handleKeyDown);
    };
  }, [handleBack]);

  return (
    <main
      role="main"
      aria-labelledby="system-logs-title"
      className="min-h-[calc(100vh-8rem)] bg-bg px-3 py-4 text-text sm:px-6 sm:py-6 lg:px-8 lg:py-8"
    >
      <div className="mx-auto flex max-w-7xl flex-col gap-5 sm:gap-6">
        <header className="flex flex-col gap-4 sm:gap-5 lg:flex-row lg:items-start lg:justify-between">
          <div className="min-w-0 flex-1">
            <span className="inline-flex items-center rounded-full bg-primary/10 px-3 py-1 text-xs font-bold uppercase tracking-wider text-primary">
              System Telemetry
            </span>

            <h1
              id="system-logs-title"
              className="mt-3 text-2xl font-bold tracking-tight sm:text-3xl lg:text-4xl"
            >
              System Logs
            </h1>

            <p className="mt-3 max-w-3xl text-sm leading-relaxed text-text/60 lg:text-base">
              Review security events, runtime telemetry, synchronization history, and operational
              diagnostics generated by your secure vault environment.
            </p>
          </div>
          <div className="flex items-center gap-2.5 sm:gap-3 shrink-0">
            <Button
              variant="outline"
              onClick={handleBack}
              className="h-10 sm:h-11 flex-1 sm:flex-initial justify-center rounded-xl border border-card-border bg-card-bg px-4 text-xs sm:text-sm text-text/85 hover:bg-text/5 hover:text-text"
            >
              <ArrowLeft className="mr-2 h-4 w-4 shrink-0" />
              Back
            </Button>
          </div>
        </header>

        <Suspense fallback={<SystemLogsLoading />}>
          <SystemLogsCard />
        </Suspense>
      </div>
    </main>
  );
};

SystemLogsPage.displayName = 'SystemLogsPage';

export { SystemLogsPage };
export default memo(SystemLogsPage);
